local auth = require "ldbus.auth"
local mock = require "mock_socket"

describe("ldbus.auth", function()
  it("performs the EXTERNAL handshake and returns the GUID", function()
    local io_obj = mock.new({ replies = { "OK 0123456789abcdef0123456789abcdef\r\n" } })
    local guid, err = auth.negotiate(io_obj, "31303030")
    assert.is_nil(err)
    assert.equals("0123456789abcdef0123456789abcdef", guid)
    assert.equals("\0" .. "AUTH EXTERNAL 31303030\r\n" .. "BEGIN\r\n", io_obj:sent())
  end)

  it("sends the NUL byte before the AUTH line", function()
    local io_obj = mock.new({ replies = { "OK abc\r\n" } })
    auth.negotiate(io_obj, "30")
    assert.equals("\0", io_obj.written[1]:sub(1, 1))
  end)

  it("fails on REJECTED", function()
    local io_obj = mock.new({ replies = { "REJECTED EXTERNAL DBUS_COOKIE_SHA1\r\n" } })
    local guid, err = auth.negotiate(io_obj, "30")
    assert.is_nil(guid)
    assert.truthy(err:find("rejected"))
  end)

  it("fails on ERROR response", function()
    local io_obj = mock.new({ replies = { "ERROR bad parameter\r\n" } })
    local guid, err = auth.negotiate(io_obj, "30")
    assert.is_nil(guid)
    assert.truthy(err:find("unexpected"))
  end)

  it("fails on DATA response", function()
    local io_obj = mock.new({ replies = { "DATA 3030\r\n" } })
    local guid, err = auth.negotiate(io_obj, "30")
    assert.is_nil(guid)
    assert.truthy(err:find("unexpected"))
  end)

  it("fails on connection close", function()
    local io_obj = mock.new({})
    local guid, err = auth.negotiate(io_obj, "30")
    assert.is_nil(guid)
    assert.truthy(err:find("closed"))
  end)

  it("handles replies split across chunks via the buffer", function()
    local io_obj = mock.new({ replies = { "OK 1234", "\r\n" } })
    local guid, err = auth.negotiate(io_obj, "30")
    assert.is_nil(err)
    assert.equals("1234", guid)
  end)
end)
