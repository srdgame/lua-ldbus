local address = require "ldbus.address"

describe("ldbus.address", function()
  describe("parse", function()
    it("parses unix:path", function()
      local t = address.parse("unix:path=/tmp/session-bus")
      assert.same({ transport = "unix", path = "/tmp/session-bus" }, t)
    end)

    it("parses unix abstract", function()
      local t = address.parse("unix:abstract=/tmp/dbus-xyz")
      assert.same({ transport = "unix", abstract = "/tmp/dbus-xyz" }, t)
    end)

    it("parses tcp", function()
      local t = address.parse("tcp:host=localhost,port=1234,family=ipv4")
      assert.same({ transport = "tcp", host = "localhost", port = "1234", family = "ipv4" }, t)
    end)

    it("skips unsupported transports and picks a later entry", function()
      local t = address.parse("nonce-tcp:host=x,port=1;unix:path=/real/bus")
      assert.same({ transport = "unix", path = "/real/bus" }, t)
    end)

    it("strips guid key gracefully", function()
      local t = address.parse("unix:path=/tmp/b,guid=abcdef0123")
      assert.equals("/tmp/b", t.path)
      assert.equals("abcdef0123", t.guid)
    end)

    it("rejects empty input", function()
      local t, err = address.parse("")
      assert.is_nil(t)
      assert.truthy(err)
      local t2, err2 = address.parse(nil)
      assert.is_nil(t2)
      assert.truthy(err2)
    end)

    it("rejects unsupported-only addresses", function()
      local t, err = address.parse("nonce-tcp:host=x,port=1")
      assert.is_nil(t)
      assert.truthy(err:find("unsupported"))
    end)

    it("rejects unix without path or abstract", function()
      local t, err = address.parse("unix:guid=x")
      assert.is_nil(t)
      assert.truthy(err:find("path"))
    end)
  end)

  describe("get", function()
    it("reads DBUS_SESSION_BUS_ADDRESS", function()
      local t = address.get("session", { DBUS_SESSION_BUS_ADDRESS = "unix:path=/s" })
      assert.equals("/s", t.path)
    end)

    it("falls back to DBUS_STARTER_ADDRESS (dbus-run-session)", function()
      local t = address.get("session", { DBUS_STARTER_ADDRESS = "unix:abstract=/starter" })
      assert.equals("/starter", t.abstract)
    end)

    it("errors when session address missing", function()
      local t, err = address.get("session", {})
      assert.is_nil(t)
      assert.truthy(err:find("DBUS_SESSION_BUS_ADDRESS"))
    end)

    it("uses system default path", function()
      local t = address.get("system", {})
      assert.equals("/var/run/dbus/system_bus_socket", t.path)
    end)

    it("honors DBUS_SYSTEM_BUS_ADDRESS", function()
      local t = address.get("system", { DBUS_SYSTEM_BUS_ADDRESS = "unix:path=/custom" })
      assert.equals("/custom", t.path)
    end)

    it("rejects unknown bus types", function()
      local t, err = address.get("blorp", {})
      assert.is_nil(t)
      assert.truthy(err:find("unknown bus type"))
    end)
  end)
end)
