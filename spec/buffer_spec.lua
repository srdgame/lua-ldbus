local Buffer = require "ldbus.buffer"

describe("ldbus.buffer", function()
  describe("take", function()
    it("accumulates small chunks until n bytes are available", function()
      local b = Buffer.new()
      b:feed("hel")
      assert.is_nil(b:take(5))
      b:feed("lo w")
      assert.equals("hello", b:take(5))
      b:feed("orld")
      assert.equals(" w", b:take(2))
      assert.equals("orld", b:take(4))
    end)

    it("consumes exactly n bytes", function()
      local b = Buffer.new()
      b:feed("abcdef")
      assert.equals("abc", b:take(3))
      assert.equals("def", b:take(3))
      assert.is_nil(b:take(1))
    end)

    it("ignores nil/false/empty feeds", function()
      local b = Buffer.new()
      b:feed(nil)
      b:feed(false)
      b:feed("")
      assert.equals(0, b:available())
    end)
  end)

  describe("read_line", function()
    it("returns complete \\r\\n-terminated lines", function()
      local b = Buffer.new()
      b:feed("OK 1234\r\nBEGIN\r\n")
      assert.equals("OK 1234\r\n", b:read_line())
      assert.equals("BEGIN\r\n", b:read_line())
      assert.is_nil(b:read_line())
    end)

    it("buffers partial lines", function()
      local b = Buffer.new()
      b:feed("OK 12")
      assert.is_nil(b:read_line())
      b:feed("34\r\n")
      assert.equals("OK 1234\r\n", b:read_line())
    end)

    it("handles lines split across many feeds", function()
      local b = Buffer.new()
      for c in ("AUTH\r\n"):gmatch(".") do
        b:feed(c)
        if c ~= "\n" then
          assert.is_nil(b:read_line())
        end
      end
      assert.equals("AUTH\r\n", b:read_line())
    end)
  end)

  describe("peek", function()
    it("peeks without consuming", function()
      local b = Buffer.new()
      b:feed("0123456789")
      assert.equals("012", b:peek(3))
      assert.equals(10, b:available())
      assert.is_nil(b:peek(11))
    end)
  end)

  describe("message frame accumulation", function()
    it("supports the header-length take pattern", function()
      -- simulate: read 16-byte fixed header to learn the total size
      local b = Buffer.new()
      b:feed("\1\1\0\1\0\0\0\0") -- half a header
      assert.is_nil(b:take(16))
      b:feed("\8\0\0\0\1\0\0\0")
      local header = b:take(16)
      assert.equals(16, #header)
      -- body length from header byte 4..8 = 8
      assert.is_nil(b:take(8))
      b:feed("abcdefgh")
      assert.equals("abcdefgh", b:take(8))
    end)
  end)
end)
